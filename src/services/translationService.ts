export async function translateText(
  text: string,
  targetLang: LanguageCode,
  isOnline = true
): Promise<TranslationResult> {
  const clean = text.trim();

  // Try offline dictionary first for exact phrases
  if (OFFLINE_LEXICON[clean]?.[targetLang]) {
    return {
      originalText: text,
      translatedText: OFFLINE_LEXICON[clean][targetLang],
      targetLang,
      source: 'offline-lexicon',
    };
  }

  // If online, call server API (which invokes Gemini 3.8 Flash)
  if (isOnline && typeof fetch !== 'undefined') {
    try {
      const response = await fetch('/api/translate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          text: clean,
          targetLang,
          islGloss: false,
        }),
      });

      if (response.ok) {
        const data = await response.json();
        return {
          originalText: text,
          translatedText: data.translatedText || text,
          targetLang,
          source: data.source || 'gemini-3.8-flash',
        };
      }
    } catch (e) {
      console.warn('Network translation failed, using fallback:', e);
    }
  }

  // Fallback if not online or not matched
  return {
    originalText: text,
    translatedText: text,
    targetLang,
    source: 'local-fallback',
  };
}
